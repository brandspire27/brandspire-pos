import assert from 'node:assert/strict';
import { readPhotoBatch, savePhotoBatch } from '../src/lib/product-photo-batch.ts';
const row=i=>({id:crypto.randomUUID(),name:`Product ${i}`,selling_price:10+i,stock:1,unit:'pcs',tax_rate:0,tax_inclusive:false,selected:true,state:'draft'});
let state={rows:Array.from({length:20},(_,i)=>row(i)),unresolved:['Check blurry text']};
const sent=[];
const persist=value=>{state=readPhotoBatch(JSON.stringify(value));};
await assert.rejects(savePhotoBatch(state,persist,async product=>{sent.push(product.id);if(sent.length===6)throw Error('Lost response');}),/Lost response/);
assert.equal(state.rows.filter(r=>r.state==='saved').length,5);
assert.equal(state.rows[5].state,'pending');
const pendingId=state.rows[5].id;
const next=[];await savePhotoBatch(state,persist,async product=>next.push(product.id));
assert.equal(next[0],pendingId);assert.equal(next.length,15);
assert.equal(state.rows.filter(r=>r.state==='saved').length,20);
await savePhotoBatch(state,persist,async()=>{throw Error('Saved products must not be sent again');});
const invalid={rows:[{...row(21),selling_price:null}],unresolved:[]};
await assert.rejects(savePhotoBatch(invalid,()=>{},async()=>{throw Error('Should never send');}),/Enter a name/);
await assert.rejects(savePhotoBatch({rows:[row(1)],unresolved:[]},()=>{throw Error('Storage full');},async()=>{throw Error('Must persist first');}),/Storage full/);
assert.throws(()=>readPhotoBatch(JSON.stringify({rows:[row(1),{...row(2),id:'invalid'}],unresolved:[]})),/could not be read/);
console.log('20-row import, partial failure, stable retry, no duplicate resend, missing price and storage failure passed.');
