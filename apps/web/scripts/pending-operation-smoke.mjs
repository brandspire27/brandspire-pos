import assert from 'node:assert/strict';
import {runPendingOperation} from '../src/lib/pending-operation.ts';
const saved=new Map();
const storage={getItem:k=>saved.get(k)??null,setItem:(k,v)=>saved.set(k,v),removeItem:k=>saved.delete(k)};
let writes=0;const server=new Map();let firstId;
const payload={amount:20,method:'CASH'};
const send=async body=>{firstId??=body.operationId;if(!server.has(body.operationId)){writes++;server.set(body.operationId,{ok:true});}return server.get(body.operationId);};
await assert.rejects(runPendingOperation(storage,'user:shop:payment',payload,async body=>{await send(body);throw new Error('Response lost');}),/lost/);
await assert.rejects(runPendingOperation(storage,'user:shop:payment',{amount:30},send),/unconfirmed/);
assert.equal(writes,1);
await assert.rejects(runPendingOperation(storage,'user:shop:payment',payload,async()=>{throw Object.assign(new Error('Session expired'),{status:401});}));
assert.equal(saved.size,1,'A later authorization failure must not discard an earlier unknown result');
await runPendingOperation(storage,'user:shop:payment',payload,async body=>{assert.equal(body.operationId,firstId);return send(body);});
assert.equal(writes,1);assert.equal(saved.size,0);
await runPendingOperation(storage,'user:shop:payment',payload,send);
assert.equal(writes,2,'An acknowledged action permits a deliberately new action');
await assert.rejects(runPendingOperation(storage,'rejected',payload,async()=>{throw Object.assign(new Error('Invalid'),{status:400});}));
assert.equal(saved.has('rejected'),false);
await assert.rejects(runPendingOperation({...storage,setItem(){throw new Error('Storage full');}},'blocked',payload,send),/Storage full/);
assert.equal(writes,2);
console.log('Pending operation tests passed: lost response, persisted replay, changed-details block, acknowledged new operation, rejection and storage failure. Browser lock/device acceptance remains separate.');
